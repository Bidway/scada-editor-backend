package com.example.scriptcore;

/**
 * Скрипт фоновой задачи пишется как тело функции: {@code return} на верхнем уровне допустим —
 * регулятору естественно выйти из такта раньше («ручной режим — записал и вышел»).
 * <p>
 * Обёртка одна на проверку в {@code editor} и исполнение в {@code automation}: разойдись они,
 * скрипт, прошедший проверку, падал бы при исполнении. Результат {@link #wrap} — выражение,
 * вычисление которого даёт функцию; вызывает её исполнитель.
 * <p>
 * {@code \n} перед закрывающей скобкой обязателен: без него строчный комментарий в последней
 * строке пользователя закомментировал бы саму скобку.
 */
public final class TaskScriptSource {

    /** Сколько строк обёртка добавляет перед текстом пользователя — для пересчёта номера строки ошибки. */
    public static final int PREFIX_LINES = 1;

    private TaskScriptSource() {
    }

    public static String wrap(String script) {
        return "(function(){\n" + (script == null ? "" : script) + "\n})";
    }
}
