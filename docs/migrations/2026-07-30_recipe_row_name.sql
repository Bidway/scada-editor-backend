-- Наборы значений таблиц: ключ строки — имя свойства вместо тега, плюс вид набора.
--
-- Зачем руками: ddl-auto: update не добавляет NOT NULL-колонку в непустую таблицу и не удаляет
-- старую. При старте Hibernate попытается и молча (в лог) откажется — схема останется прежней,
-- а сохранение набора упадёт. Выполнять до запуска обновлённого editor.
--
-- Существовавшие наборы были тестовыми и удаляются: их значения ключевались тегом, а часть
-- уже не находила своих строк. Переносить нечего.

BEGIN;

DELETE FROM editor.recipe_value;
DELETE FROM editor.recipe;

-- Вид набора: рецепт под продукт, параметры станции и т.д. (см. RecipeTypes).
ALTER TABLE editor.recipe ADD COLUMN IF NOT EXISTS type varchar(255) NOT NULL;

-- Ключ значения: имя строки таблицы вместо тега. Имя переживает пересохранение таблицы
-- (id строк при нём пересоздаются) и перепривязку строки на другой тег, а строки без тега
-- (локальные параметры) вообще нельзя адресовать тегом.
ALTER TABLE editor.recipe_value ADD COLUMN IF NOT EXISTS row_name varchar(255) NOT NULL;
ALTER TABLE editor.recipe_value DROP COLUMN IF EXISTS tag_id;

COMMIT;
